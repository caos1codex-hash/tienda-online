// Helpers
export const getProductBySlug = (slug) => PRODUCTS.find((p) => p.slug === slug)
export const getProductById = (id) => PRODUCTS.find((p) => p.id === id)
export const getByCategory = (cat) => PRODUCTS.filter((p) => p.category === cat)
export const getFeatured = () => PRODUCTS.filter((p) => p.tags.includes('Destacado'))
export const getNew = () => PRODUCTS.filter((p) => p.tags.includes('Nuevo') || p.badge === 'Nuevo')
export const getPopular = () => [...PRODUCTS].sort((a, b) => b.popularity - a.popularity).slice(0, 8)
export const getRelated = (product, limit = 4) =>
  PRODUCTS.filter((p) => p.category === product.category && p.id !== product.id).slice(0, limit)
