// ============ HELPERS ============

export function getProductBySlug(slug) {
  return PRODUCTS.find((p) => p.slug === slug) || null
}

export function getProductsByCategory(categoryId) {
  return PRODUCTS.filter((p) => p.category === categoryId)
}

export function getFeatured() {
  return PRODUCTS.filter((p) => p.badge === 'Nuevo' || p.tags.includes('Destacado')).slice(0, 8)
}

export function getPopular() {
  return [...PRODUCTS].sort((a, b) => b.popularity - a.popularity).slice(0, 8)
}

export function getRelated(product) {
  return PRODUCTS.filter((p) => p.category === product.category && p.id !== product.id)
    .sort((a, b) => b.popularity - a.popularity)
    .slice(0, 4)
}

export function getMoreSold() {
  return [...PRODUCTS].sort((a, b) => (b.soldThisWeek || 0) - (a.soldThisWeek || 0)).slice(0, 8)
}

export function getOffers() {
  return PRODUCTS.filter((p) => p.oldPrice).slice(0, 8)
}
